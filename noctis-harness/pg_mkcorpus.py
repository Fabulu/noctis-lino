def main():
    out = {
        "pg_corpus_raster.txt": raster(),
        "pg_corpus_edge.txt":   edge(),
        "pg_corpus_span.txt":   span(),
        "pg_corpus_proj.txt":   proj(),
    }
    import hashlib
    for name, text in out.items():
        path = os.path.join(HERE, name)
        with open(path, "w", newline="\n") as f:
            f.write(text)
        n = sum(1 for ln in text.splitlines()
                if ln.strip() and not ln.startswith("#"))
        print("%-24s %5d rows  sha256=%s"
              % (name, n, hashlib.sha256(text.encode()).hexdigest()[:16]))


if __name__ == "__main__":
    main()
