# ================================================================= edge ======

def edge():
    L = []
    A = L.append
    A("# pg_corpus_edge.txt -- surface S4 (polymap ipart/fpart edge walk)")
    A("#")
    A("# FROZEN FIXTURE.  Generated by pg_mkcorpus.py.")
    A("#")
    A("# GRAMMAR:  EDGE <id> n= mp=x0,y0;... miny= maxy=")
    A("#")
    A("# ipart[] is the LEFT boundary (seeded ubxl=311); fpart[] is the RIGHT")
    A("# boundary (seeded lbxl=5).  TDPOLYGS.H:2539.  The names are inverted")
    A("# relative to the obvious reading.")
    A("#")
    A("# miny/maxy are PINNED inputs, not recomputed from mp[].  In polymap they")
    A("# come from the projector's y-only extent after the two normalisation")
    A("# steps at :2487-2499, which is a different quantity from min(mp.y).")
    A("")

    def E(idn, pts, y0, y1):
        A("EDGE %s n=%d mp=%s miny=%d maxy=%d" % (idn, len(pts), mpstr(pts), y0, y1))

    E("ED_TRI",        [(50,30),(200,60),(120,150)], 30, 150)
    E("ED_QUAD",       [(50,30),(200,40),(210,150),(40,140)], 30, 150)
    E("ED_ABOVE_TOP",  [(50,-40),(200,-30),(120,150)], 10, 150)
    E("ED_CROSS_TOP",  [(50,-5),(200,20),(120,150)], 10, 150)
    E("ED_CROSS_BOT",  [(50,30),(200,60),(120,260)], 30, 190)
    E("ED_BOTH",       [(50,-100),(200,-90),(120,400)], 10, 190)
    E("ED_ONESCAN",    [(50,100),(200,101),(120,101)], 100, 101)
    E("ED_HORIZ",      [(50,100),(200,100),(120,150)], 100, 150)
    E("ED_TALL",       [(60,10),(70,190),(200,100)], 10, 190)
    E("ED_CLAMP_LEFT", [(-40000,50),(200,60),(120,150)], 50, 150)
    E("ED_CLAMP_RIGHT",[(40000,50),(200,60),(120,150)], 50, 150)
    A("# bndx landing exactly on k+0.5 at every scanline: dx/dy = 1/2 with an")
    A("# odd start, so the accumulator alternates .0 and .5.  This is the")
    A("# nearest-even site a truncating port gets wrong.")
    E("ED_TIE_HALF",   [(51,20),(101,120),(60,120)], 20, 120)
    E("ED_TIE_HALF2",  [(50,20),(100,120),(61,120)], 20, 120)
    A("# quarter steps: .25/.5/.75 sequence, only one of four rows is a tie")
    E("ED_TIE_QTR",    [(50,20),(75,120),(60,120)], 20, 120)
    A("# negative slope, so a truncating port biases the other way")
    E("ED_NEG_SLOPE",  [(200,20),(150,120),(210,120)], 20, 120)
    A("# long edge: 170 scanlines of accumulator drift")
    E("ED_DRIFT",      [(20,10),(300,180),(25,180)], 10, 180)
    E("ED_DRIFT_REV",  [(300,10),(20,180),(295,180)], 10, 180)
    A("# mp[] above 2**24, as a blown-up near-plane interpolation produces")
    E("ED_HUGE",       [(20000000,50),(200,60),(120,150)], 50, 150)
    A("# ity == jty exactly, reachable only through the top clip: an edge from")
    A("# y=5 to y=10 has ity=lbyl=10 and jty=10, and `jnl noifor` (ity>=jty)")
    A("# makes it contribute NOTHING.  The source comment says h<=jty; the code")
    A("# says otherwise.")
    E("ED_ITY_EQ_JTY", [(60,5),(120,10),(200,60)], 10, 60)
    A("# ED_ITY_EQ_JTY only moves the record if the skipped edge would have")
    A("# contributed a value no OTHER edge already covers.  When the edge ends")
    A("# on a shared vertex at y=lbyl the next edge starts from the same x, so")
    A("# the write is absorbed.  Here BOTH edges incident on the y=10 vertex")
    A("# come from above it, so both are skipped and row 10 keeps its seeds")
    A("# (ipart=311, fpart=5, an empty span).  `<=` would fill it with 160:160")
    A("# and the polygon would stop vanishing.")
    E("ED_ITY_EQ_JTY2", [(20,2),(300,2),(160,10)], 10, 20)
    A("# top clip landing on an exact half: kx = 5/20 = 0.25 exactly, so")
    A("# (lbyl-y1)*kx = 10*0.25 = 2.5 exactly and x1 = 51 is ODD.  Rounding the")
    A("# SUM gives rne(53.5) = 54; rounding the PRODUCT first gives 51+2 = 53.")
    A("# This single row is what separates the two.")
    E("ED_TIE_TOPCLIP", [(51,0),(56,20),(200,100)], 10, 100)
    E("ED_TIE_TOPCLIP2",[(53,0),(58,20),(200,100)], 10, 100)
    A("# closing edge mp[vr22] = mp[0] must be walked too")
    E("ED_CLOSING",    [(200,30),(210,150),(50,60)], 30, 150)
    return "\n".join(L) + "\n"


# ================================================================= span ======

def span():
    L = []
    A = L.append
    A("# pg_corpus_span.txt -- surface S5 (polymap span engine)")
    A("#")
    A("# FROZEN FIXTURE.  Generated by pg_mkcorpus.py.")
    A("#")
    A("# GRAMMAR:")
    A("#   SPAN <id> i= ipart= fpart= tinta= escr= flares= cull= half= maxy=")
    A("#             tex= uv=u0,v0;u1,v1;... pre=")
    A("#")
    A("# uv[] is the ORDERED list of the row's (u,v) values as int32: pair 0 is")
    A("# the value computed at `trace` before the first block, pair k>=1 is the")
    A("# value after block k's `fistp u / fistp v`.  Block k reads pair k-1 into")
    A("# EAX/EDX and derives its per-pixel step as (pair[k]-pair[k-1]) >> 4,")
    A("# a 32-bit arithmetic shift; the accumulators themselves are 16-BIT")
    A("# (`add ax,bp` carries no 0x66 prefix).")
    A("#")
    A("# TEXTURES (formulas over the 64 KiB window reachable through fs:[bx]):")
    A("#   TEX0  t[i] = (i*37 + 11) & 255")
    A("#   TEX1  t[i] = ((i>>8) ^ (i & 255)) & 255")
    A("#   TEX2  t[i] = 1")
    A("#   TEX3  t[i] = 0 except t[0]=t[32768]=t[65535]=255")
    A("#")
    A("# escr defaults to 0xE0.  The two scratch pixels adapted[63996]/[63997]")
    A("# (es:[0xFA00]/[0xFA01]) carry tinta and escrescenze and are present in")
    A("# every case as a canary.")
    A("")

    def uvlist(u0, v0, du, dv, nblk):
        # nblk+1 pairs are consumed; two spares are appended so that a sabotage
        # which lengthens the span (e.g. a right-inclusive `sections`) still
        # has input and fails on the PAGE rather than on a parse error.
        return ";".join("%d,%d" % (u0 + k*du, v0 + k*dv) for k in range(nblk+3))

    def S(idn, i, ip, fp, uv, tinta=0, escr=0xE0, fl=0, cull=0, half=0,
          tex="TEX0", pre="PRE0", maxy=None):
        my = maxy if maxy is not None else i+1
        A("SPAN %s i=%d ipart=%d fpart=%d tinta=%d escr=%d flares=%d cull=%d "
          "half=%d maxy=%d tex=%s uv=%s pre=%s"
          % (idn, i, ip, fp, tinta, escr, fl, cull, half, my, tex, uv, pre))

    # block-boundary classes (non-culling: 16 px per block)
    S("SP_SHORT",   100, 100, 105, uvlist(0, 0, 16*64, 16*32, 1))
    S("SP_EXACT16", 100, 100, 116, uvlist(0, 0, 16*64, 16*32, 1))
    S("SP_EXACT17", 100, 100, 117, uvlist(0, 0, 16*64, 16*32, 2))
    S("SP_EXACT32", 100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2))
    S("SP_EXACT33", 100, 100, 133, uvlist(0, 0, 16*64, 16*32, 3))
    S("SP_LONG",    100,   6, 310, uvlist(0, 0, 16*64, 16*32, 20))
    S("SP_ZERO",    100, 100, 100, uvlist(0, 0, 0, 0, 1))
    S("SP_NEGSEC",  100, 150, 120, uvlist(0, 0, 0, 0, 1))

    # accumulator wrap
    S("SP_UWRAP",   100, 100, 132, uvlist(0x0FFF0, 0, 16*0x100, 0, 2))
    S("SP_VWRAP",   100, 100, 132, uvlist(0, 0x0FFF0, 0, 16*0x100, 2))
    S("SP_FULLWRAP",100, 100, 132, uvlist(0x0FF00, 0x0FF00, 16*0x180, 16*0x180, 2))
    S("SP_NEGSTEP", 100, 100, 132, uvlist(0x8000, 0x8000, -16*0x40, -16*0x20, 2))
    A("# step_u negative and not a multiple of 16: sar 4 truncates toward -inf")
    S("SP_SARTRUNC",100, 100, 132, uvlist(0x8000, 0x8000, -17, -33, 2))

    # texture probes
    S("SP_TEX1",    100, 100, 132, uvlist(0, 0, 16*257, 16*257, 2), tex="TEX1")
    S("SP_TEX2",    100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2),   tex="TEX2")
    S("SP_TEX3",    100, 100, 132, uvlist(0, 0, 16*0x101, 16*0x101, 2), tex="TEX3")

    # combine variants -- each with a NON-ZERO pre-state, since four of the
    # five read the destination
    for name, fl in (("INT",0),("TRANSP",1),("BRIGHT",2),("MERGER",4),("BUMP",8)):
        S("SP_%s" % name,  100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2),
          tinta=0x11, fl=fl, pre="PRE1")
        S("SP_%s_P0" % name, 102, 100, 132, uvlist(0, 0, 16*64, 16*32, 2),
          tinta=0x11, fl=fl, pre="PRE0")
    A("# bright clamps at 0x3E, not 0x3F")
    S("SP_BRIGHT_CLAMP", 100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2),
      tinta=0, fl=2, tex="TEX0", pre="PRE1")
    A("# merger's 8-bit `or` bleeds the shifted value into the top 2 bits")
    S("SP_MERGER_BLEED", 100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2),
      tinta=0xC0, fl=4, pre="PRE1")
    A("# bumper with n=(tinta+texel)&7 == 0 writes one row BELOW; n==1 writes")
    A("# the SAME row.  TEX2 makes every texel 1, so n = (tinta+1)&7.")
    S("SP_BUMP_N0", 100, 100, 116, uvlist(0, 0, 16*64, 16*32, 1),
      tinta=7, fl=8, tex="TEX2", pre="PRE1")
    S("SP_BUMP_N1", 100, 100, 116, uvlist(0, 0, 16*64, 16*32, 1),
      tinta=0, fl=8, tex="TEX2", pre="PRE1")
    S("SP_BUMP_N7", 100, 100, 116, uvlist(0, 0, 16*64, 16*32, 1),
      tinta=6, fl=8, tex="TEX2", pre="PRE1")

    # flares dispatch is a bit test WITH PRIORITY, not a switch.
    A("# groundflares = 2 + 2*cz reaches 2,4,6,8 (NOCTIS-1.CPP:1986) and feeds")
    A("# polymap, whose dispatch is a bit test with priority.  6 and 10")
    A("# exercise the priority order: 6 must take the BRIGHT arm, not MERGER.")
    S("SP_FL6",  100, 100, 132, uvlist(0, 0, 16*64, 16*32, 2), tinta=0x11, fl=6, pre="PRE1")
